export function kvRows(rows, { htmlValues = false } = {}) {
  return `<div class="kv">${rows.map(([key, value, mono = false]) => {
    let rendered = value;
    if (value !== undefined && value !== null && value !== '') {
      // Values generated by badge()/progress() are trusted markup and opt in
      // explicitly. Everything else is escaped when it contains a raw tag.
      // Pre-escaped entity text (for example "&lt;") is left untouched, so a
      // caller cannot accidentally double-escape it.
      if (!htmlValues && /[<>]/.test(String(value))) rendered = esc(value);
    } else {
      rendered = '—';
    }
    return `<div class="kv-row"><span class="kv-key">${esc(key)}</span><span class="kv-value${mono ? ' mono' : ''}">${rendered}</span></div>`;
  }).join('')}</div>`;
}

